export interface ScriptLine {
  speaker: string; // e.g., "男の人", "女の人", "先生", "アナウンサー"
  speakerType: "male" | "female" | "announcer" | "teacher" | "other";
  text: string;
  furiganaText?: string;
  vietnamese: string;
}

export interface ExamSection {
  id: string; // e.g. "intro-exam", "intro-m1", "intro-m2", "intro-m3", "intro-m4"
  type: "exam_intro" | "mondai_intro";
  mondai?: 1 | 2 | 3 | 4;
  title: string;
  titleJapanese: string;
  timeStart: number;
  timeEnd: number;
  timestampDisplay: string;
  description: string;
  descriptionVietnamese: string;
  script: ScriptLine[];
}

export interface ListeningQuestion {
  id: string; // e.g. "m1-1", "m2-3"
  mondai: 1 | 2 | 3 | 4;
  mondaiTitle: string;
  questionNumber: number | string; // e.g. 1 or "例"
  isExample?: boolean;
  timeStart: number; // in seconds
  timeEnd: number; // in seconds
  timestampDisplay: string; // e.g. "03:24"
  title: string; // Short title description
  situation: string; // Prompt situation
  situationVietnamese: string;
  questionText: string;
  questionVietnamese: string;
  options: {
    number: number;
    text: string;
    vietnamese: string;
  }[];
  correctAnswer: number; // 1-indexed (1, 2, 3, or 4)
  script: ScriptLine[];
  explanation: string;
  keyVocabulary: string[];
}

